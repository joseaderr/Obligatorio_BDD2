CREATE OR REPLACE TRIGGER TRG_RESENA_LUGAR
    AFTER INSERT OR UPDATE ON RESENA
BEGIN
    UPDATE LUGAR l
    SET puntos = (
        SELECT NVL(AVG(r.puntaje), 0)
        FROM RESENA r
        JOIN CUENTA c ON c.id_cuenta = r.id_cuenta
        WHERE r.id_lugar = l.id_lugar
          AND c.estado <> 'Suspendida'
    );
END;




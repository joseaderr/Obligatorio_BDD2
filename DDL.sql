-- A. Restricción de Operación (Cuentas Suspendidas)
CREATE OR REPLACE TRIGGER TRG_RESENA_CUENTA_ACTIVA
BEFORE INSERT OR UPDATE ON RESENA
FOR EACH ROW
DECLARE
    v_estado CUENTA.estado%TYPE;
BEGIN
    SELECT estado INTO v_estado FROM CUENTA WHERE id_cuenta = :new.id_cuenta;
    IF v_estado = 'Suspendida' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Error: Una cuenta suspendida no puede publicar reseñas.');
    END IF;
END;


-- B. Límite Diario de Reseñas (Tope de 5 por fecha)
CREATE OR REPLACE TRIGGER TRG_RESENA_LIMITE_DIARIO
BEFORE INSERT ON RESENA
FOR EACH ROW
DECLARE
    v_cantidad NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_cantidad
    FROM RESENA
    WHERE id_cuenta = :new.id_cuenta AND TRUNC(fecha) = TRUNC(:new.fecha);

    IF v_cantidad >= 5 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Error: Se ha alcanzado el límite máximo de 5 reseñas diarias por cuenta.');
    END IF;
END;


-- C. Lugar Cerrado Definitivamente
CREATE OR REPLACE TRIGGER TRG_RESENA_LUGAR_OPERATIVO
BEFORE INSERT ON RESENA
FOR EACH ROW
DECLARE
    v_estado LUGAR.estado%TYPE;
BEGIN
    SELECT estado INTO v_estado FROM LUGAR WHERE id_lugar = :new.id_lugar;
    IF v_estado = 'Cerrado definitivamente' THEN
        RAISE_APPLICATION_ERROR(-20003, 'Error: No se admiten reseñas para establecimientos cerrados definitivamente.');
    END IF;
END;


-- D. No Auto-Like (Validación con el ID único de Reseña)
CREATE OR REPLACE TRIGGER TRG_ME_GUSTA_NO_AUTOLIKE
BEFORE INSERT OR UPDATE ON ME_GUSTA
FOR EACH ROW
DECLARE
    v_id_autor_resena RESENA.id_cuenta%TYPE;
BEGIN
    SELECT id_cuenta INTO v_id_autor_resena FROM RESENA WHERE id_resena = :new.id_resena;

    IF :new.id_cuenta_mg = v_id_autor_resena THEN
        RAISE_APPLICATION_ERROR(-20006, 'Error: Un usuario no puede dar Me Gusta a su propia reseña.');
    END IF;
END;


-- E. Coherencia Temporal de Respuesta
CREATE OR REPLACE TRIGGER TRG_RESPUESTA_COHERENCIA_TEMP
BEFORE INSERT OR UPDATE ON RESPUESTA
FOR EACH ROW
DECLARE
    v_fecha_resena DATE;
BEGIN
    SELECT fecha INTO v_fecha_resena FROM RESENA WHERE id_resena = :new.id_resena;

    IF :new.fecha_publicacion < v_fecha_resena THEN
        RAISE_APPLICATION_ERROR(-20004, 'Error: La respuesta no puede tener una fecha anterior a la de la reseña.');
    END IF;
END;


-- F. Autorización de Respuesta (Propietario Administrador)
CREATE OR REPLACE TRIGGER TRG_RESPUESTA_AUTORIZACION
BEFORE INSERT OR UPDATE ON RESPUESTA
FOR EACH ROW
DECLARE
    v_id_admin LUGAR.id_cuenta_admin%TYPE;
BEGIN
    SELECT l.id_cuenta_admin INTO v_id_admin
    FROM RESENA r
    JOIN LUGAR l ON r.id_lugar = l.id_lugar
    WHERE r.id_resena = :new.id_resena;

    IF v_id_admin IS NULL OR v_id_admin <> :new.id_cuenta_prop THEN
        RAISE_APPLICATION_ERROR(-20005, 'Error: Solo el propietario administrador asignado a este lugar puede responder.');
    END IF;
END;


